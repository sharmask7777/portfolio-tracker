import type { HarvestOpportunityDto } from '../../types/generated/HarvestOpportunityDto';
import type { HarvestTicketResponse } from '../../types/generated/HarvestTicketResponse';

export function getDaysUntilFYEndIST(): { daysRemaining: number; fyString: string } {
  const formatter = new Intl.DateTimeFormat('en-US', {
    timeZone: 'Asia/Kolkata',
    year: 'numeric',
    month: 'numeric',
    day: 'numeric',
    hour12: false,
  });

  const now = new Date();
  const parts = formatter.formatToParts(now);
  let year = now.getFullYear();
  let month = now.getMonth() + 1;

  for (const part of parts) {
    if (part.type === 'year') year = parseInt(part.value, 10);
    if (part.type === 'month') month = parseInt(part.value, 10);
  }

  const endYear = month <= 3 ? year : year + 1;
  const startYear = endYear - 1;
  const fyString = `FY ${startYear}-${endYear.toString().slice(-2)}`;

  const fyEndUtc = new Date(Date.UTC(endYear, 2, 31, 18, 29, 59));
  const diffMs = fyEndUtc.getTime() - now.getTime();
  const daysRemaining = Math.max(0, Math.ceil(diffMs / (1000 * 60 * 60 * 24)));

  return { daysRemaining, fyString };
}

function formatOpportunityLine(op: HarvestOpportunityDto, index: number, orderCount: number): string {
  const unitsStr = typeof op.unitsToHarvest === 'number' && Number.isFinite(op.unitsToHarvest)
    ? op.unitsToHarvest.toFixed(3)
    : '0.000';
  const lotsSummary = op.lotsCount && op.lotsCount > 1
    ? ` • FIFO Scope: Consolidates ${op.lotsCount} monthly SIP lots` +
      (op.firstLotDate && op.lastLotDate ? ` (${op.firstLotDate} to ${op.lastLotDate})` : '')
    : ' • FIFO Scope: Single purchase lot (>365 days LTCG)';

  return [
    `\n[ORDER ${index + 1} of ${orderCount}]`,
    `• Scheme: ${op.schemeName}`,
    `• Folio No: ${op.folioNumber || op.folioId || 'Primary Folio'}`,
    `• Action: Redeem ${unitsStr} units (Approx. Value: ₹${(op.currentValue ?? 0).toLocaleString('en-IN')})`,
    `• Tax-Free Gain Harvested: ₹${(op.unrealizedGain ?? 0).toLocaleString('en-IN')}`,
    lotsSummary,
  ].join('\n');
}

export function formatHarvestInstructions(ticket: HarvestTicketResponse): string {
  const fyInfo = getDaysUntilFYEndIST();
  const orderCount = ticket.opportunities.length;
  const lines: string[] = [
    '=============================================================',
    '  SECTION 112A TAX-FREE HARVESTING REDEMPTION INSTRUCTIONS',
    '=============================================================',
    `Financial Year: ${fyInfo.fyString} | Target: Sec 112A ₹1,25,000 Tax-Free LTCG`,
    `Remaining Statutory Exemption: ₹${(ticket.remainingExemption ?? 0).toLocaleString('en-IN')}`,
    `Total Tax-Free Gains to Harvest: ₹${(ticket.totalPotentialHarvest ?? 0).toLocaleString('en-IN')}`,
    `Estimated Tax Saved (12.5%): ₹${(ticket.estimatedTaxSavings ?? 0).toLocaleString('en-IN')}`,
    'Execution Hub: MF Central / CAMS / KFintech (Redeem by Units)',
    '',
    `ACTIONABLE REDEMPTIONS (Only ${orderCount} ${orderCount === 1 ? 'Order' : 'Orders'} Needed):`,
  ];

  ticket.opportunities.forEach((op, index) => {
    lines.push(formatOpportunityLine(op, index, orderCount));
  });

  lines.push(
    '',
    '-------------------------------------------------------------',
    `TOTAL TURNOVER: ₹${ticket.opportunities.reduce((acc, op) => acc + (op.currentValue ?? 0), 0).toLocaleString('en-IN')} | TOTAL TAX-FREE GAIN: ₹${(ticket.totalPotentialHarvest ?? 0).toLocaleString('en-IN')}`,
    '-------------------------------------------------------------',
    'REINVESTMENT ADVISORY:',
    '• Settled proceeds credit your bank in T+2 business days.',
    '• DO NOT repurchase into ELSS (avoids fresh 3-year statutory lock-in).',
    '• Reinvest the proceeds into an open-ended equity fund (e.g. Nifty 50 Index Fund)',
    '  to step-up your tax cost basis to current NAV with ZERO lock-in.',
    'CBDT Sec 112A Compliant · Generated by Portfolio Tracker',
    '============================================================='
  );

  return lines.join('\n');
}
